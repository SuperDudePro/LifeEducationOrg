import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import ts from "typescript";
import { APPROVED_SOURCES } from "../api/ask/source-manifest.mjs";

const ROOT = process.cwd();
const OUTPUT = path.join(ROOT, "api", "ask", "corpus.generated.mjs");
const MAX_CHUNK = 2800;

function loadExport(source, exportName, filename) {
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: filename,
  }).outputText;
  const module = { exports: {} };
  vm.runInNewContext(compiled, { exports: module.exports, module }, { filename });
  const value = module.exports[exportName];
  if (!value) throw new Error(`${filename} does not export ${exportName}.`);
  return value;
}

function collectStrings(value, output = []) {
  if (typeof value === "string") output.push(value.trim());
  else if (typeof value === "number") output.push(String(value));
  else if (Array.isArray(value)) value.forEach((item) => collectStrings(item, output));
  else if (value && typeof value === "object") {
    Object.entries(value).forEach(([key, item]) => {
      if (!["id", "slug", "href", "image", "icon"].includes(key)) collectStrings(item, output);
    });
  }
  return output.filter(Boolean);
}

function splitText(text) {
  const paragraphs = text.split(/\n+/).map((part) => part.trim()).filter(Boolean);
  const chunks = [];
  let current = "";
  for (const paragraph of paragraphs) {
    if (current && current.length + paragraph.length + 2 > MAX_CHUNK) {
      chunks.push(current);
      current = "";
    }
    if (paragraph.length > MAX_CHUNK) {
      if (current) chunks.push(current);
      for (let index = 0; index < paragraph.length; index += MAX_CHUNK) {
        chunks.push(paragraph.slice(index, index + MAX_CHUNK));
      }
    } else {
      current = current ? `${current}\n\n${paragraph}` : paragraph;
    }
  }
  if (current) chunks.push(current);
  return chunks;
}

function sectionRecords(source, data) {
  if (source.id === "qa") {
    return [
      { heading: "Introduction", value: data.intro },
      ...data.sections.flatMap((section) => section.items.map((item) => ({
        heading: `${section.heading}: ${item.question}`,
        value: item.answer,
      }))),
      { heading: "Bottom line", value: data.bottom },
    ];
  }
  if (source.id === "domains") {
    return data.map((domain) => ({
      heading: `Domain ${domain.number}: ${domain.title}`,
      value: domain,
    }));
  }
  return [
    { heading: "Introduction", value: data.intro },
    ...(data.sections ?? []).map((section) => ({
      heading: section.heading ?? section.title ?? section.id ?? source.title,
      value: section,
    })),
  ];
}

const chunks = [];
for (const source of APPROVED_SOURCES) {
  const filename = path.join(ROOT, source.operationalCopy);
  const file = await readFile(filename, "utf8");
  const data = loadExport(file, source.exportName, filename);
  for (const record of sectionRecords(source, data)) {
    const text = collectStrings(record.value).join("\n");
    splitText(text).forEach((part, index) => {
      chunks.push({
        id: `${source.id}:${chunks.filter((chunk) => chunk.sourceId === source.id).length + 1}`,
        sourceId: source.id,
        title: source.title,
        heading: index ? `${record.heading} (part ${index + 1})` : record.heading,
        authority: source.authority,
        authorityRank: source.authorityRank,
        topic: source.topic,
        publicUrl: source.publicUrl,
        text: part,
      });
    });
  }
}

const publicSources = APPROVED_SOURCES.map((source) => {
  const { exportName, operationalCopy, ...metadata } = source;
  return metadata;
});
const contents = [
  "// Generated by scripts/build-ask-corpus.mjs. Do not edit by hand.",
  `export const SOURCES = ${JSON.stringify(publicSources, null, 2)};`,
  `export const CORPUS = ${JSON.stringify(chunks, null, 2)};`,
  "",
].join("\n");

await mkdir(path.dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, contents, "utf8");
console.log(`Ask corpus written: ${publicSources.length} approved sources, ${chunks.length} chunks.`);
